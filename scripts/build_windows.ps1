# =====================================================================================
#  build_windows.ps1 - LedgerStitch Windows build (PyInstaller onedir + Inno Setup)
#
#  *** UNTESTED. Written on macOS without a Windows machine; expect to fix small
#  *** things on the first real run. Keep the steps in sync with build_macos.sh.
#
#  Usage (PowerShell, from the repo root):
#     powershell -ExecutionPolicy Bypass -File scripts\build_windows.ps1
#     $env:SKIP_SMOKE = "1"; .\scripts\build_windows.ps1
#     $env:EDITION = "pro"; .\scripts\build_windows.ps1   # default "community" (AGPL core only)
#     $env:SIGN_PFX = "C:\path\cert.pfx"; $env:SIGN_PFX_PASSWORD = "..."   # optional signing
#
#  Requires: Windows 10/11 x64, uv (https://docs.astral.sh/uv/) on PATH,
#            Inno Setup 6 (iscc.exe) for the installer step (optional).
#  Outputs:  dist\LedgerStitch\LedgerStitch.exe (onedir),
#            dist\LedgerStitch-<version>-Windows-x64-Setup.exe, + .sha256
# =====================================================================================
$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")
$Root = (Get-Location).Path

$Version = (Select-String -Path "ledgerstitch\__init__.py" -Pattern '__version__\s*=\s*"([^"]+)"').Matches[0].Groups[1].Value
# --- 0a. edition + numeric version (mirrors build_macos.sh) ---------------------------
$Edition = if ($env:EDITION) { $env:EDITION.Trim().ToLower() } else { "community" }
if ($Edition -notin @("community", "pro")) { throw "EDITION must be community or pro" }
$env:EDITION = $Edition                                   # read by packaging\ledgerstitch.spec
$Suffix = if ($Edition -eq "pro") { "-Pro" } else { "" }
# Windows version resources need a.b.c.d numbers: "1.2.0rc1" -> "1.2.0.0"
$VerParts = @(($Version -replace '^(\d+(\.\d+)*).*$', '$1').Split(".") | Select-Object -First 4)
while ($VerParts.Count -lt 4) { $VerParts += "0" }
$VersionNum = $VerParts -join "."
Write-Host "==> LedgerStitch $Version $Edition edition (Windows x64)"

# --- 1. release venv (never the dev venv) --------------------------------------------
# separate venvs so a community build can never pick up the proprietary add-on
$Venv = if ($Edition -eq "pro") { Join-Path $Root ".venv-release-win-pro" } else { Join-Path $Root ".venv-release-win" }
$Py = Join-Path $Venv "Scripts\python.exe"
if (-not (Get-Command uv -ErrorAction SilentlyContinue)) { throw "uv not found. Install: powershell -c `"irm https://astral.sh/uv/install.ps1 | iex`"" }
if ($env:REFRESH_VENV -eq "1" -or -not (Test-Path $Py)) {
    if (Test-Path $Venv) { Remove-Item -Recurse -Force $Venv }
    uv venv --python 3.12 $Venv
}
uv pip install --python $Py --only-binary :all: -e ".[build]" -q
if ($Edition -eq "pro") {
    if (-not (Test-Path "pro\pyproject.toml")) { throw "EDITION=pro needs the private pro\ package checked out" }
    # non-editable: the frozen app needs real dist-info (entry point) and the package files
    uv pip install --python $Py --only-binary :all: ".\pro" -r packaging\addon_requirements.txt -q
    & $Py -c "import PyInstaller, ledgerstitch_pro, tkinter"
} else {
    # PS 5.1 turns redirected native stderr into errors; don't let "not installed" stop us
    $eap = $ErrorActionPreference; $ErrorActionPreference = "Continue"
    uv pip uninstall --python $Py ledgerstitch-pro -q 2>&1 | Out-Null
    if (Test-Path "packaging\addon_requirements.txt") { uv pip uninstall --python $Py -r packaging\addon_requirements.txt -q 2>&1 | Out-Null }
    $ErrorActionPreference = $eap
    & $Py -c "import PyInstaller, tkinter"
}
if ($LASTEXITCODE -ne 0) { throw "build deps missing" }

# --- 1b. edition constant (read by ledgerstitch\editions.py; removed again at the end) -
"# SPDX-License-Identifier: AGPL-3.0-only`n# generated by scripts/build_windows.ps1`nEDITION = `"$Edition`"`n" |
    Set-Content -NoNewline -Encoding ASCII "ledgerstitch\_edition.py"
# try/finally (not re-indented, to keep the diff small) guarantees _edition.py is removed
try {

# --- 2. clean + icon -----------------------------------------------------------------
Remove-Item -Recurse -Force build, dist -ErrorAction SilentlyContinue
& $Py packaging\make_icon.py

# --- 3. PyInstaller ------------------------------------------------------------------
& $Py -m PyInstaller packaging\ledgerstitch.spec --distpath dist --workpath build --noconfirm --clean --log-level WARN
if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed" }
$Exe = "dist\LedgerStitch\LedgerStitch.exe"

# --- 3a. edition boundary (mirrors build_macos.sh 4a) --------------------------------
Write-Host "==> checking the $Edition bundle contents"
$bundled = Get-ChildItem -Recurse -Force "dist\LedgerStitch" | ForEach-Object { $_.FullName }
if ($Edition -eq "community") {
    $leak = $bundled | Where-Object { $_ -match 'ledgerstitch_[a-z]+|\\anthropic\\' }
    if ($leak) { $leak | Select-Object -First 10 | Write-Host; throw "the Community bundle contains proprietary add-on code or cloud AI SDKs" }
} else {
    if (-not ($bundled | Where-Object { $_ -match 'ledgerstitch_pro' })) { throw "Pro bundle lacks ledgerstitch_pro" }
}
Write-Host "    OK"

# --- 4. smoke test -------------------------------------------------------------------
# Windowed (no-console) exe: stdout is not attached, so capture via Start-Process redirection.
if ($env:SKIP_SMOKE -ne "1") {
    $out = Join-Path $env:TEMP "ledgerstitch-selftest.txt"
    $p = Start-Process -FilePath $Exe -ArgumentList "--self-test" -Wait -PassThru -NoNewWindow -RedirectStandardOutput $out
    Get-Content $out
    if ($p.ExitCode -ne 0) { throw "self-test failed" }

    $data = Join-Path $env:TEMP ("ledgerstitch-smoke-" + [guid]::NewGuid())
    $srv = Start-Process -FilePath $Exe -ArgumentList "--no-browser","--no-window","--port","8799","--data-dir",$data -PassThru
    $sw = [Diagnostics.Stopwatch]::StartNew(); $ok = $false
    while ($sw.Elapsed.TotalSeconds -lt 30 -and -not $ok) {
        try { $r = Invoke-WebRequest -UseBasicParsing "http://127.0.0.1:8799/"; $ok = $r.StatusCode -eq 200 } catch { Start-Sleep -Milliseconds 100 }
    }
    Write-Host ("    startup to HTTP: {0:N2}s" -f $sw.Elapsed.TotalSeconds)
    if (-not $ok -or $r.Content -notmatch "<title>LedgerStitch") { Stop-Process $srv; throw "GET / failed" }
    try { Invoke-WebRequest -UseBasicParsing "http://127.0.0.1:8799/api/status" | Out-Null; Stop-Process $srv; throw "expected 401" }
    catch { if ($_.Exception.Response.StatusCode.value__ -ne 401) { Stop-Process $srv; throw "expected 401, got: $_" } }
    Stop-Process $srv   # hard kill on Windows (no SIGTERM); the vault is re-locked on next open
    Write-Host "    smoke test OK"
}

# --- 5. code signing (needs an OV/EV code-signing certificate; placeholder) ----------
# signtool sign /fd sha256 /tr http://timestamp.digicert.com /td sha256 /a "dist\LedgerStitch\LedgerStitch.exe"

# --- 5a. optional signing from env: SIGN_PFX (path to .pfx) + SIGN_PFX_PASSWORD --------
# Used by .github/workflows/release-community.yml when the Windows certificate secrets exist.
$SignTool = $null
if ($env:SIGN_PFX) {
    if (-not (Test-Path $env:SIGN_PFX)) { throw "SIGN_PFX does not exist: $env:SIGN_PFX" }
    $SignTool = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin" -Recurse -Filter signtool.exe -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -match '\\x64\\' } | Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
    if (-not $SignTool) { throw "signtool.exe not found (install the Windows 10/11 SDK)" }
    $SignArgs = @("sign", "/fd", "sha256", "/tr", "http://timestamp.digicert.com", "/td", "sha256", "/f", $env:SIGN_PFX, "/p", $env:SIGN_PFX_PASSWORD)
    Write-Host "==> signing executables with $SignTool"
    $toSign = Get-ChildItem -Recurse "dist\LedgerStitch" -Include *.exe | ForEach-Object { $_.FullName }
    & $SignTool @SignArgs @toSign
    if ($LASTEXITCODE -ne 0) { throw "signtool failed" }
}

# --- 6. installer (Inno Setup) -------------------------------------------------------
$Iscc = @("${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe", "$env:ProgramFiles\Inno Setup 6\ISCC.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if ($Iscc) {
    $IsccArgs = @("/DAppVersion=$Version", "/DAppVersionNum=$VersionNum", "/DEditionSuffix=$Suffix")
    if ($SignTool) {   # Inno signs Setup.exe and the uninstaller ($f = file, $q = quote)
        $IsccArgs += @("/DUseSignTool", "/Ssigntool=`$q$SignTool`$q sign /fd sha256 /tr http://timestamp.digicert.com /td sha256 /f `$q$($env:SIGN_PFX)`$q /p `$q$($env:SIGN_PFX_PASSWORD)`$q `$f")
    }
    & $Iscc @IsccArgs "/DSourceDir=$Root\dist\LedgerStitch" "/O$Root\dist" packaging\ledgerstitch.iss
    if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed" }
    $Setup = "dist\LedgerStitch$Suffix-$Version-Windows-x64-Setup.exe"
    # signtool sign /fd sha256 /tr http://timestamp.digicert.com /td sha256 /a $Setup   (done by Inno via 5a)
    $h = (Get-FileHash -Algorithm SHA256 $Setup).Hash.ToLower()
    "$h  $(Split-Path $Setup -Leaf)" | Set-Content "$Setup.sha256"
    Write-Host "    installer: $Setup ($([math]::Round((Get-Item $Setup).Length/1MB,1)) MB)  sha256 $h"
} else {
    Write-Warning "Inno Setup 6 not found - skipping installer. Install from https://jrsoftware.org/isinfo.php"
}
$size = (Get-ChildItem -Recurse dist\LedgerStitch | Measure-Object -Sum Length).Sum / 1MB
Write-Host ("==> done. onedir: dist\LedgerStitch ({0:N0} MB)" -f $size)

# --- end of 1b: remove the generated edition constant, even when a step failed --------
} finally {
    Remove-Item -Force -ErrorAction SilentlyContinue (Join-Path $Root "ledgerstitch\_edition.py")
}
