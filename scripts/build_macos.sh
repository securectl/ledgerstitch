#!/usr/bin/env bash
# Build LedgerStitch.app and LedgerStitch-<version>-macOS-<arch>.dmg with PyInstaller.
#
#   scripts/build_macos.sh                  # clean build, ad-hoc signed
#   SKIP_SMOKE=1 scripts/build_macos.sh     # skip the post-build self-test
#   MACOS_MIN=13.0 scripts/build_macos.sh   # raise the minimum macOS (default 12.0)
#   REFRESH_VENV=1 scripts/build_macos.sh   # recreate the release venv (pick up new deps)
#   EDITION=community scripts/build_macos.sh   # default: AGPL core only (no AI add-on, no AI SDKs)
#   EDITION=pro scripts/build_macos.sh         # core + ledgerstitch_pro wheel (unlocks with a key)
#   DMG_FANCY=0 scripts/build_macos.sh         # plain DMG (no background/icon layout; see 7a)
#
# Builds from a dedicated release venv (.venv-release, never the dev .venv) whose wheels are
# resolved for MACOSX_DEPLOYMENT_TARGET=$MACOS_MIN, so the app really runs on that macOS.
# (The newest numpy/onnxruntime wheels need macOS 14; uv picks older compatible ones.)
#
# Outputs: dist/LedgerStitch.app, dist/LedgerStitch-<version>-macOS-<arch>.dmg (+ .sha256)
# Requires: macOS, uv (https://docs.astral.sh/uv/) at ~/.local/bin/uv or on PATH, network on first run.
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd)"
UV="${UV:-$(command -v uv || echo "$HOME/.local/bin/uv")}"
export MACOS_MIN="${MACOS_MIN:-12.0}"
export EDITION="${EDITION:-community}"
case "$EDITION" in community|pro) ;; *) echo "EDITION must be community or pro" >&2; exit 1 ;; esac
# separate venvs so a community build can never pick up the proprietary add-on
if [ "$EDITION" = "pro" ]; then VENV="$ROOT/.venv-release-pro"; else VENV="$ROOT/.venv-release"; fi
PY="$VENV/bin/python"

VERSION="$(sed -nE 's/^__version__ *= *"([^"]+)".*/\1/p' ledgerstitch/__init__.py)"
ARCH="$(uname -m)"
case "$ARCH" in arm64) UVPLAT=aarch64-apple-darwin ;; *) UVPLAT=x86_64-apple-darwin ;; esac
APP="dist/LedgerStitch.app"
if [ "$EDITION" = "pro" ]; then SUFFIX="-Pro"; else SUFFIX=""; fi
DMG="dist/LedgerStitch${SUFFIX}-${VERSION}-macOS-${ARCH}.dmg"
echo "==> LedgerStitch ${VERSION} ${EDITION} edition (${ARCH}, macOS >= ${MACOS_MIN})"

# --- 1. release venv -------------------------------------------------------------------------
[ -x "$UV" ] || { echo "uv not found; install it: curl -LsSf https://astral.sh/uv/install.sh | sh" >&2; exit 1; }
if [ "${REFRESH_VENV:-0}" = "1" ] || [ ! -x "$PY" ]; then
  echo "==> creating release venv (wheels for macOS ${MACOS_MIN})"
  rm -rf "$VENV"
  "$UV" venv --python 3.12 "$VENV"
fi
MACOSX_DEPLOYMENT_TARGET="$MACOS_MIN" "$UV" pip install --python "$PY" \
  --python-platform "$UVPLAT" --only-binary :all: -e ".[build]" -q
if [ "$EDITION" = "pro" ]; then
  [ -f pro/pyproject.toml ] || { echo "EDITION=pro needs the private pro/ package checked out" >&2; exit 1; }
  # --- compiled private add-ons --------------------------------------------------------------
  # Pro is shipped ONLY as a compiled native wheel (never readable .py/.pyc); see
  # scripts/compile_private.py (private repo). Build the wheel in the dedicated
  # .venv-compile (same Python 3.12 as this release venv, so the cp312 tag matches) and install
  # it + the cloud SDKs here. The wheel carries real dist-info, so the entry point resolves.
  echo "==> compiling the Pro add-on to a native wheel"
  MACOS_MIN="$MACOS_MIN" scripts/compile_private.sh pro
  PRO_WHEEL="$(ls -t dist/private/ledgerstitch_pro-*.whl 2>/dev/null | head -1)"
  [ -n "$PRO_WHEEL" ] || { echo "ERROR: compiled Pro wheel not found in dist/private/" >&2; exit 1; }
  "$UV" pip install --python "$PY" --no-deps --reinstall "$PRO_WHEEL" -q
  # the add-on's runtime dependencies (listed by the private build tooling)
  MACOSX_DEPLOYMENT_TARGET="$MACOS_MIN" "$UV" pip install --python "$PY" \
    --python-platform "$UVPLAT" --only-binary :all: -r packaging/addon_requirements.txt -q
  "$PY" -c "import ledgerstitch_pro; assert ledgerstitch_pro.__file__.endswith('.so'), ledgerstitch_pro.__file__"
  # --- end compiled private add-ons ----------------------------------------------------------
  "$PY" -c "import PyInstaller, ledgerstitch_pro"
  "$PY" -m ledgerstitch.desktop --self-test >/dev/null || { echo "ERROR: add-on dependencies missing (self-test)" >&2; exit 1; }
else
  "$UV" pip uninstall --python "$PY" ledgerstitch-pro -q 2>/dev/null || true
  [ -f packaging/addon_requirements.txt ] && "$UV" pip uninstall --python "$PY" -r packaging/addon_requirements.txt -q 2>/dev/null || true
  "$PY" -c "import PyInstaller"
fi

# build-time edition constant (read by ledgerstitch/editions.py); removed again on exit
printf '# SPDX-License-Identifier: AGPL-3.0-only\n# generated by scripts/build_macos.sh\nEDITION = "%s"\n' "$EDITION" \
  > ledgerstitch/_edition.py
trap 'rm -f "$ROOT/ledgerstitch/_edition.py"' EXIT

# --- 2. clean ------------------------------------------------------------------------------
echo "==> cleaning build/ and dist/"
rm -rf build dist

# --- 3. icon -------------------------------------------------------------------------------
echo "==> rendering icon"
"$PY" packaging/make_icon.py

# --- 4. PyInstaller ------------------------------------------------------------------------
echo "==> PyInstaller (onedir, windowed)"
T0=$(date +%s)
"$PY" -m PyInstaller packaging/ledgerstitch.spec --distpath dist --workpath build --noconfirm --clean --log-level WARN
echo "    built in $(( $(date +%s) - T0 ))s"
rm -rf dist/LedgerStitch   # the bare onedir folder; the .app holds the same files

# --- 4a. edition boundary ------------------------------------------------------------------
echo "==> checking the ${EDITION} bundle contents"
if [ "$EDITION" = "community" ]; then
  if find "$APP" -ipath '*ledgerstitch_*' -o -ipath '*/anthropic/*' | grep -q .; then   # any add-on package
    echo "ERROR: the Community bundle contains proprietary add-on code or cloud AI SDKs" >&2; exit 1
  fi
else
  find "$APP" -ipath '*ledgerstitch_pro*' | grep -q . || { echo "ERROR: Pro bundle lacks ledgerstitch_pro" >&2; exit 1; }
fi
echo "    OK"

# --- 4c. compiled private add-ons: no .py/.pyc, not in the PYZ -----------------------------
# The proprietary add-ons must appear only as compiled extension modules. Fail if any
# add-on (ledgerstitch_<name>) .py or .pyc leaked into the bundle, or if any of them landed
# in PyInstaller's PYZ archive (pure-Python modules are stored there as .pyc).
echo "==> checking private add-ons are compiled-only (no .py/.pyc, not in PYZ)"
LEAK="$(find "$APP" -type f \( -name '*.py' -o -name '*.pyc' \) \
          -ipath '*ledgerstitch_*' || true)"
if [ -n "$LEAK" ]; then
  echo "ERROR: proprietary add-on shipped as readable .py/.pyc:" >&2; echo "$LEAK" | head -20 >&2; exit 1
fi
"$PY" - "$APP/Contents/MacOS/LedgerStitch" <<'PYZCHECK'
import sys
exe = sys.argv[1]
private = ("ledgerstitch_",)   # every add-on package (the core is plain "ledgerstitch")
try:
    from PyInstaller.archive.readers import CArchiveReader
    car = CArchiveReader(exe)
    toc = car.get_table_of_contents() if hasattr(car, "get_table_of_contents") else car.toc
    names = list(toc.keys()) if isinstance(toc, dict) else [e[-1] for e in toc]
    pyz_name = next((n for n in names if n.endswith(".pyz") or n == "PYZ-00.pyz"), None)
    bad = []
    if pyz_name is not None:
        data = car.extract(pyz_name)
        raw = data[1] if isinstance(data, tuple) else data
        import io
        from PyInstaller.archive.readers import ZlibArchiveReader
        tmp = io.BytesIO(raw) if isinstance(raw, (bytes, bytearray)) else None
        # Fall back to scanning the raw PYZ bytes for module names (reader APIs vary by version).
        blob = raw if isinstance(raw, (bytes, bytearray)) else b""
        for p in private:
            if p.encode() in blob:
                bad.append(p)
    if bad:
        print("ERROR: private package(s) found in the PYZ archive (should be binary .so):", bad, file=sys.stderr)
        sys.exit(1)
    print("    PYZ archive is clean of private packages")
except Exception as e:  # noqa: BLE001 - archive reader APIs differ across PyInstaller versions
    print(f"    (could not introspect PYZ via PyInstaller reader: {e}; relying on the .py/.pyc scan)")
PYZCHECK
echo "    OK"

# --- 4b. every Mach-O must load on MACOS_MIN ------------------------------------------------
echo "==> checking binaries' minimum macOS (<= ${MACOS_MIN})"
TOO_NEW="$(find "$APP" -type f \( -name '*.so' -o -name '*.dylib' -o -perm -111 \) -print0 |
  xargs -0 file | grep Mach-O | cut -d: -f1 | while read -r f; do
    v="$(otool -l "$f" | awk '/LC_BUILD_VERSION/{b=1} b&&/minos/{print $2; exit}')"
    [ -n "$v" ] && [ "$(printf '%s\n%s\n' "$v" "$MACOS_MIN" | sort -V | tail -1)" != "$MACOS_MIN" ] && echo "$v ${f#"$APP"/}"
  done || true)"
if [ -n "$TOO_NEW" ]; then
  echo "ERROR: these binaries need a newer macOS than ${MACOS_MIN}:" >&2; echo "$TOO_NEW" | head -20 >&2
  echo "Run with REFRESH_VENV=1, or raise MACOS_MIN." >&2; exit 1
fi
if find "$APP" -type f \( -name '*.so' -o -name '*.dylib' \) -exec otool -L {} \; 2>/dev/null |
   grep -v ':$' | awk '{print $1}' | grep -v '^@\|^/usr/lib\|^/System' | grep -q .; then
  echo "ERROR: a bundled library links outside the bundle (would fail on a clean Mac)" >&2; exit 1
fi
echo "    OK"

# --- 5. ad-hoc codesign --------------------------------------------------------------------
# Ad-hoc signature: required on Apple Silicon for the binaries to run at all. Not trusted by
# Gatekeeper on other Macs (users must right-click > Open, or run `xattr -dr com.apple.quarantine`).
echo "==> ad-hoc codesign"
codesign --force --deep -s - "$APP"
codesign --verify --deep --strict "$APP" && echo "    signature OK (ad-hoc)"

# --- 5b. REAL SIGNING (Developer ID) — uncomment once a certificate exists ----------------
# Prereqs (one time): Apple Developer Program membership ($99/yr); create a
# "Developer ID Application" certificate in Xcode > Settings > Accounts > Manage Certificates
# (or developer.apple.com), and an app-specific password at appleid.apple.com. Then:
#   xcrun notarytool store-credentials ledgerstitch-notary \
#       --apple-id "FOUNDER_APPLE_ID@example.com" --team-id "TEAMID1234" --password "abcd-efgh-ijkl-mnop"
#
# IDENTITY="Developer ID Application: YOUR NAME (TEAMID1234)"
# ENT="packaging/entitlements.plist"
# # Sign inside-out: every nested Mach-O first, then the main executable, then the bundle.
# find "$APP/Contents" -type f \( -name "*.so" -o -name "*.dylib" -o -perm -111 \) -print0 |
#   while IFS= read -r -d '' f; do
#     if file "$f" | grep -q "Mach-O"; then
#       codesign --force --options runtime --timestamp --entitlements "$ENT" -s "$IDENTITY" "$f"
#     fi
#   done
# codesign --force --options runtime --timestamp --entitlements "$ENT" -s "$IDENTITY" "$APP"
# codesign --verify --deep --strict --verbose=2 "$APP"
# spctl --assess --type execute --verbose "$APP"     # expect "rejected (Unnotarized...)" until notarized

# --- 5c. real signing from env (used by CI; same recipe as 5b) -----------------------------
# IDENTITY="Developer ID Application: NAME (TEAMID)" must be in the keychain search list.
if [ -n "${IDENTITY:-}" ]; then
  echo "==> Developer ID signing: $IDENTITY"
  ENT="packaging/entitlements.plist"
  find "$APP/Contents" -type f \( -name "*.so" -o -name "*.dylib" -o -perm -111 \) -print0 |
    while IFS= read -r -d '' f; do
      if file "$f" | grep -q "Mach-O"; then
        codesign --force --options runtime --timestamp --entitlements "$ENT" -s "$IDENTITY" "$f"
      fi
    done
  codesign --force --options runtime --timestamp --entitlements "$ENT" -s "$IDENTITY" "$APP"
  codesign --verify --deep --strict --verbose=2 "$APP"
fi

# --- 6. smoke test (bundled executable) ----------------------------------------------------
if [ "${SKIP_SMOKE:-0}" != "1" ]; then
  echo "==> self-test of bundled executable"
  "$APP/Contents/MacOS/LedgerStitch" --self-test
fi

# --- 7. DMG --------------------------------------------------------------------------------
echo "==> building DMG"
STAGE="build/dmg"
rm -rf "$STAGE"; mkdir -p "$STAGE"
cp -R "$APP" "$STAGE/"
ln -s /Applications "$STAGE/Applications"

# --- 7a. DMG layout (optional) ---------------------------------------------------------------
# Background with an arrow + icon positions, set through Finder (AppleScript) on a read-write
# image that is then converted to UDZO. Needs a GUI login session (Finder); on headless CI or
# any failure it falls back to the plain DMG below. DMG_FANCY=0 skips it.
# DMG_LAYOUT_BEGIN (marker for tests; keep the function self-contained)
dmg_fancy() {  # dmg_fancy STAGE_DIR OUT_DMG VOLNAME PYTHON
  local stage="$1" out="$2" vol="$3" py="$4" work="build/dmg-fancy" rw mnt disk
  rw="$work/rw.dmg"
  rm -rf "$work"; mkdir -p "$work" "$stage/.background"
  "$py" packaging/make_dmg_background.py "$work" >/dev/null || return 1
  tiffutil -cathidpicheck "$work/background.png" "$work/background@2x.png" \
    -out "$stage/.background/background.tiff" >/dev/null 2>&1 || return 1
  hdiutil create -volname "$vol" -srcfolder "$stage" -fs HFS+ -format UDRW \
    -size "$(( $(du -sm "$stage" | cut -f1) + 20 ))m" -ov "$rw" >/dev/null || return 1
  # no -nobrowse: Finder must see the volume. The mount point may get a " 1" suffix.
  mnt="$(hdiutil attach -readwrite -noverify -noautoopen "$rw" | awk -F'\t' '/\/Volumes\//{print $NF; exit}')"
  [ -n "$mnt" ] || return 1
  disk="$(basename "$mnt")"
  osascript - "$disk" >/dev/null 2>&1 <<'APPLESCRIPT' &
on run argv
  with timeout of 60 seconds
    tell application "Finder"
      tell disk (item 1 of argv)
        open
        set current view of container window to icon view
        set toolbar visible of container window to false
        set statusbar visible of container window to false
        set the bounds of container window to {200, 120, 860, 548}
        set opts to the icon view options of container window
        set arrangement of opts to not arranged
        set icon size of opts to 128
        set text size of opts to 13
        set background picture of opts to file ".background:background.tiff"
        set position of item "LedgerStitch.app" of container window to {165, 184}
        set position of item "Applications" of container window to {495, 184}
        update without registering applications
        delay 2
        close
      end tell
    end tell
  end timeout
end run
APPLESCRIPT
  local osa=$! ok=1
  for _ in $(seq 1 90); do kill -0 "$osa" 2>/dev/null || break; sleep 1; done
  if kill -0 "$osa" 2>/dev/null; then kill "$osa" 2>/dev/null; ok=0; fi   # hung (no GUI / no permission)
  wait "$osa" 2>/dev/null || ok=0
  sync
  [ -f "$mnt/.DS_Store" ] || ok=0                       # Finder never wrote the layout
  rm -rf "$mnt/.fseventsd" "$mnt/.Trashes"
  for _ in 1 2 3 4; do hdiutil detach "$mnt" -quiet && break; sleep 2; done
  if [ -d "$mnt" ]; then hdiutil detach "$mnt" -force -quiet || return 1; fi
  [ "$ok" = 1 ] || return 1
  hdiutil convert "$rw" -format UDZO -imagekey zlib-level=9 -ov -o "$out" >/dev/null || return 1
  rm -rf "$work"
}
# DMG_LAYOUT_END
FANCY_OK=0
if [ "${DMG_FANCY:-1}" != "0" ]; then
  if dmg_fancy "$STAGE" "$DMG" "LedgerStitch ${VERSION}" "$PY"; then
    FANCY_OK=1; echo "    DMG layout: background + icon positions"
  else
    echo "    DMG layout skipped (no Finder/GUI session?); building a plain DMG"
    rm -rf "$STAGE/.background" build/dmg-fancy "$DMG"
  fi
fi
if [ "$FANCY_OK" = 0 ]; then
hdiutil create -volname "LedgerStitch ${VERSION}" -srcfolder "$STAGE" -ov -format UDZO \
  -imagekey zlib-level=9 "$DMG" >/dev/null
fi
rm -rf "$STAGE"
# codesign --force --timestamp -s "$IDENTITY" "$DMG"                      # (real signing)

# --- 7b. NOTARIZE + STAPLE — uncomment with real signing -----------------------------------
# xcrun notarytool submit "$DMG" --keychain-profile ledgerstitch-notary --wait
# #   on failure: xcrun notarytool log <submission-id> --keychain-profile ledgerstitch-notary
# xcrun stapler staple "$DMG"
# xcrun stapler staple "$APP"            # optional: also staple the .app inside dist/
# spctl --assess --type open --context context:primary-signature --verbose "$DMG"

# --- 7c. sign + notarize + staple the DMG from env (used by CI; same recipe as 7b) --------
# IDENTITY set: sign the DMG. NOTARIZE=1: notarize with an App Store Connect API key
# (NOTARY_KEY_PATH, NOTARY_KEY_ID, NOTARY_ISSUER) or a keychain profile (NOTARY_PROFILE,
# default ledgerstitch-notary), then staple. Step 8 hashes the stapled DMG.
if [ -n "${IDENTITY:-}" ]; then
  codesign --force --timestamp -s "$IDENTITY" "$DMG"
  if [ "${NOTARIZE:-0}" = "1" ]; then
    echo "==> notarizing $DMG (takes minutes)"
    if [ -n "${NOTARY_KEY_PATH:-}" ]; then
      NOTARY_AUTH=(--key "$NOTARY_KEY_PATH" --key-id "$NOTARY_KEY_ID" --issuer "$NOTARY_ISSUER")
    else
      NOTARY_AUTH=(--keychain-profile "${NOTARY_PROFILE:-ledgerstitch-notary}")
    fi
    NOTARY_OUT="$(xcrun notarytool submit "$DMG" "${NOTARY_AUTH[@]}" --wait --output-format json)"
    echo "$NOTARY_OUT"
    if ! printf '%s' "$NOTARY_OUT" | "$PY" -c 'import json,sys; sys.exit(json.load(sys.stdin).get("status") != "Accepted")'; then
      echo "ERROR: notarization was not accepted; see: xcrun notarytool log <id> ${NOTARY_AUTH[*]}" >&2; exit 1
    fi
    xcrun stapler staple "$DMG"
    spctl --assess --type open --context context:primary-signature --verbose "$DMG"
  fi
fi

# --- 8. checksum + sizes -------------------------------------------------------------------
( cd dist && shasum -a 256 "$(basename "$DMG")" > "$(basename "$DMG").sha256" )
echo
echo "==> done"
echo "    app: $APP  ($(du -sh "$APP" | cut -f1))"
echo "    dmg: $DMG  ($(du -sh "$DMG" | cut -f1))"
echo "    sha256: $(cut -d' ' -f1 "$DMG.sha256")"
