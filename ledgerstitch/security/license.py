"""Offline license keys (Ed25519).

A license unlocks add-on features (docs/PLUGINS.md §4); it never caps the
Community core, which has no usage limits.

Key format::

    LS1.<base64url(payload_json)>.<base64url(signature)>

``payload_json`` = {"email", "plan", "expires": "YYYY-MM-DD" | null, "issued": "YYYY-MM-DD"}.
The signature covers the ASCII bytes ``"LS1." + <payload segment>`` exactly as
transmitted (no re-serialisation, so there is no canonicalisation ambiguity).

Only the PUBLIC key is embedded here. The private key lives with the seller
(scripts/gen_signing_key.py, scripts/issue_license.py) and never ships.
Verification is fully offline. ``expires`` is inclusive (valid through that day)
and checked against the local clock - an inherent limit of offline licensing.
"""
from __future__ import annotations

import base64
import binascii
import json
import logging
import os
import re
import sys
from dataclasses import dataclass
from datetime import date

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

__all__ = ["PLANS", "PLAN_ALIASES", "PLAN_RE", "DEV_PLAN_ENV", "known_plan", "dev_override_plan", "License", "LicenseError", "verify", "current_plan", "issue",
           "limits_for", "PUBLIC_KEY_B64"]

# Seller public key (generated by scripts/gen_signing_key.py). Safe to publish.
PUBLIC_KEY_B64 = "5FSg2jhHdZGw9kHwbOK8qfdU7k4gDi2E8F0Wg+eQBTk="

PREFIX = "LS1"
# A license names one plan id. The core accepts any well-formed id; which features a plan
# unlocks is decided by ledgerstitch.editions (the core's plans plus those the installed
# add-ons declare with registry.license_plans).
PLANS = ("pro", "enterprise")                  # the plans the core itself knows
PLAN_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
PLAN_ALIASES: dict[str, str] = {}               # add-ons register aliases through the plugin API
_MAX_KEY_LEN = 4096
_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")


class LicenseError(ValueError):
    """Raised by issue() for bad input. verify() never raises."""


@dataclass
class License:
    email: str
    plan: str                    # "free" or a plan id
    expires: date | None
    valid: bool
    issued: date | None = None
    reason: str = ""             # why not valid: "", "malformed", "bad signature", "expired", "unknown plan"

    @property
    def limits(self) -> dict:
        return limits_for(self.plan if self.valid else "free")

    def to_dict(self) -> dict:
        return {"email": self.email, "plan": self.plan if self.valid else "free",
                "expires": self.expires.isoformat() if self.expires else None,
                "issued": self.issued.isoformat() if self.issued else None,
                "valid": self.valid, "reason": self.reason, "limits": self.limits}


def known_plan(plan: str) -> bool:
    """A plan the core knows (PLANS) or an installed add-on declared (registry.license_plans)."""
    if not isinstance(plan, str) or not PLAN_RE.match(plan) or plan == "free":
        return False
    if plan in PLANS:
        return True
    try:
        from ..editions import plan_tiers
        return plan in plan_tiers()
    except Exception:  # noqa: BLE001 - never fail a license check on the registry
        return False


def _alias(plan: str) -> str:
    try:
        from ..editions import normalize_plan
        return normalize_plan(plan)
    except Exception:  # noqa: BLE001 - never fail a license check on the registry
        return PLAN_ALIASES.get(plan, plan)


def limits_for(plan: str) -> dict:
    """Usage limits for a plan. ``None`` means unlimited: the Community core has
    no caps on any plan (AGPL core, not crippleware).

    keys: accounts, transactions, vaults
    """
    return {"accounts": None, "transactions": None, "vaults": None}


def _free(reason: str = "", email: str = "") -> License:
    return License(email=email, plan="free", expires=None, valid=False, reason=reason)


def _b64u_enc(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode("ascii")


def _b64u_dec(s: str) -> bytes:
    if not re.fullmatch(r"[A-Za-z0-9_-]*", s):
        raise ValueError("bad base64url")
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def _public_key(public_key: bytes | None) -> Ed25519PublicKey:
    raw = public_key if public_key is not None else base64.b64decode(PUBLIC_KEY_B64)
    return Ed25519PublicKey.from_public_bytes(raw)


def verify(key: str, *, public_key: bytes | None = None, today: date | None = None) -> License:
    """Verify a license key offline. Never raises; check ``.valid``.

    ``public_key`` (raw 32 bytes) and ``today`` exist for tests only.
    """
    if not isinstance(key, str):
        return _free("malformed")
    key = "".join(key.split())          # tolerate pasted line breaks / spaces
    if not key or len(key) > _MAX_KEY_LEN:
        return _free("malformed")
    parts = key.split(".")
    if len(parts) != 3 or parts[0] != PREFIX:
        return _free("malformed")
    try:
        payload_raw = _b64u_dec(parts[1])
        sig = _b64u_dec(parts[2])
    except (ValueError, binascii.Error):
        return _free("malformed")
    try:
        _public_key(public_key).verify(sig, f"{PREFIX}.{parts[1]}".encode("ascii"))
    except (InvalidSignature, ValueError):
        return _free("bad signature")
    try:
        p = json.loads(payload_raw.decode("utf-8"))
        email = str(p["email"])
        plan = str(p["plan"])
        expires = date.fromisoformat(p["expires"]) if p.get("expires") else None
        issued = date.fromisoformat(p["issued"]) if p.get("issued") else None
    except (ValueError, KeyError, TypeError, UnicodeDecodeError):
        return _free("malformed")
    plan = _alias(plan)
    lic = License(email=email, plan=plan, expires=expires, valid=True, issued=issued)
    if not known_plan(plan):
        lic.valid, lic.reason = False, "unknown plan"
    elif expires is not None and (today or date.today()) > expires:
        lic.valid, lic.reason = False, "expired"
    return lic


DEV_PLAN_ENV = "LEDGERSTITCH_DEV_PLAN"
DEV_OVERRIDE_REASON = "developer override"
_log = logging.getLogger(__name__)
_dev_warned = False


def dev_override_plan(environ=None) -> str | None:
    """Local-testing unlock: ``LEDGERSTITCH_DEV_PLAN=<plan id>`` in the environment of a
    source (non-frozen) run. Ignored in packaged apps and for unknown plan ids. Only ever
    read from the process environment, never from a vault or settings. (A deliberate,
    documented exception to EDITIONS design rule 2, requested by the founder.)"""
    if getattr(sys, "frozen", False):
        return None
    env = os.environ if environ is None else environ
    plan = _alias((env.get(DEV_PLAN_ENV) or "").strip().lower())
    return plan if known_plan(plan) else None


def current_plan(license_key: str | None) -> License:
    """The effective license: the verified one, or a free license (valid=False,
    plan="free") if the key is missing or invalid. ``reason`` explains why.
    A developer override (see dev_override_plan) wins in source runs."""
    global _dev_warned
    dev = dev_override_plan()
    if dev:
        if not _dev_warned:
            _dev_warned = True
            _log.warning("%s=%s: developer license override active (source run only)", DEV_PLAN_ENV, dev)
        return License(email="developer@local", plan=dev, expires=None, valid=True, reason=DEV_OVERRIDE_REASON)
    if not license_key:
        return _free("")
    lic = verify(license_key)
    if lic.valid:
        return lic
    return License(email=lic.email, plan="free", expires=lic.expires, valid=False,
                   issued=lic.issued, reason=lic.reason)


def issue(private_key_pem: bytes, email: str, plan: str, expires: date | None,
          *, issued: date | None = None, password: bytes | None = None) -> str:
    """Seller side: sign a license key. ``password`` decrypts an encrypted PEM.
    A registered plan alias is signed as its canonical id."""
    plan = _alias(plan)
    if not known_plan(plan):
        raise LicenseError("plan must be a plan id (lowercase letters, digits, underscores)")
    email = (email or "").strip()
    if not _EMAIL_RE.match(email):
        raise LicenseError("invalid email")
    if expires is not None and not isinstance(expires, date):
        raise LicenseError("expires must be a date or None")
    try:
        sk = serialization.load_pem_private_key(private_key_pem, password=password)
    except (ValueError, TypeError) as e:
        raise LicenseError("could not load private key") from e
    if not isinstance(sk, Ed25519PrivateKey):
        raise LicenseError("private key is not Ed25519")
    payload = {"email": email, "plan": plan,
               "expires": expires.isoformat() if expires else None,
               "issued": (issued or date.today()).isoformat()}
    seg = _b64u_enc(json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8"))
    sig = sk.sign(f"{PREFIX}.{seg}".encode("ascii"))
    return f"{PREFIX}.{seg}.{_b64u_enc(sig)}"
